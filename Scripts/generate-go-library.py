#!/usr/bin/env python3
"""Generates what the build reads of the part of the run-time library that is Go.

The Go files under Sources/SwiftixGoLibrary are the source of truth: one
directory for each package, named by its import path. The compiler has no
file system, so the build reads their text from a Swift file, which this
script writes:

    Sources/SwiftixGo/SourceLibraryText.swift

It also writes the one Go file that is derived from another,
sort/zsortfunc.go: the sorting functions for a slice with a `less` function,
which are those of sort/sorting.go for an `Interface` with the calls of the
methods replaced, as Go generates its two families from one text.

Run it after every change to a file of the library:

    Scripts/generate-go-library.py           writes the files that changed
    Scripts/generate-go-library.py --check   writes nothing; fails if one is stale

`GoSourceLibraryFilesTests` fails as well when the Swift file is not what
the Go files say. See the guide at the top of
Sources/SwiftixGo/SourceLibrary.swift.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIBRARY = os.path.join(ROOT, "Sources", "SwiftixGoLibrary")
OUTPUT = os.path.join(ROOT, "Sources", "SwiftixGo", "SourceLibraryText.swift")

SORTING = os.path.join(LIBRARY, "sort", "sorting.go")
SORTING_FUNC = os.path.join(LIBRARY, "sort", "zsortfunc.go")


def slice_family(text):
    """The functions of sort/sorting.go for a slice and a `less` function."""
    names = re.findall(r"^func (\w+)\(data Interface", text, re.M)
    body = text.split("package sort\n", 1)[1]
    for name in names:
        body = re.sub(r"\b%s\b" % name, name + "Func", body)
    for written, meant in [
        ("data Interface", "x any, less func(i, j int) bool"),
        ("data.Less(", "less("),
        ("data.Swap(", "native.swap(x, "),
        ("(data, ", "(x, less, "),
    ]:
        body = body.replace(written, meant)
    assert "data." not in body and "(data" not in body, "sorting.go uses data in a way the slice family has no word for"
    return (
        "// Code generated by Scripts/generate-go-library.py from sorting.go; DO NOT EDIT.\n\n"
        "package sort\n" + body
    )


def declared_names(text):
    """The package-level names a file declares, as gofmt lays them out."""
    names = set()
    group = None
    for line in text.split("\n"):
        if group:
            if line == ")":
                group = None
                continue
            match = re.match(r"\t(\w+(?:, \w+)*)\b", line)
            if match:
                names.update(match.group(1).split(", "))
            continue
        match = re.match(r"(var|const|type) \($", line)
        if match:
            group = match.group(1)
            continue
        match = re.match(r"func (\w+)[(\[]", line) or re.match(r"type (\w+)\b", line)
        if match:
            names.add(match.group(1))
            continue
        match = re.match(r"(?:var|const) (\w+(?:, \w+)*)\b", line)
        if match:
            names.update(match.group(1).split(", "))
    names.discard("_")
    return names


def packages():
    """Every package of the library: its import path and its files by name."""
    found = []
    for directory, _, files in sorted(os.walk(LIBRARY)):
        sources = sorted(f for f in files if f.endswith(".go") and not f.endswith("_test.go"))
        if sources:
            path = os.path.relpath(directory, LIBRARY).replace(os.sep, "/")
            found.append((path, [(f, open(os.path.join(directory, f), encoding="utf-8").read()) for f in sources]))
    return found


def property_name(path):
    parts = re.split(r"[/_]", path)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def swift(found):
    out = []
    out.append("// Generated by Scripts/generate-go-library.py from Sources/SwiftixGoLibrary.\n")
    out.append("// Do not edit: change the Go files and run the script.\n\n")
    out.append("/// The Go text of the part of the run-time library that is compiled with the\n")
    out.append("/// program. `GoSourceLibrary` says how it is linked, and how to add to it.\n")
    out.append("///\n")
    out.append("/// A path under `$GOROOT/src` names each file in a diagnostic, which only a\n")
    out.append("/// mistake in the text can produce, and in the name of a function literal.\n")
    out.append("enum GoSourceLibraryText {\n")
    out.append("    /// The import paths that have text.\n")
    out.append("    static let paths: Set<String> = [%s]\n\n" % ", ".join('"%s"' % p for p, _ in found))
    out.append("    /// The package-level names the text of each package declares.\n")
    out.append("    static let declared: [String: Set<String>] = [\n")
    for path, files in found:
        names = set()
        for _, text in files:
            names |= declared_names(text)
        out.append('        "%s": [\n' % path)
        line = "           "
        for name in sorted(names):
            word = ' "%s",' % name
            if len(line) + len(word) > 100:
                out.append(line + "\n")
                line = "           "
            line += word
        out.append(line + "\n        ],\n")
    out.append("    ]\n\n")
    out.append("    /// The files of the package at `path`, in the order of their names.\n")
    out.append("    static func files(ofPackage path: String) -> [GoSourceFile]? {\n")
    out.append("        switch path {\n")
    for path, _ in found:
        out.append('        case "%s": return %s\n' % (path, property_name(path)))
    out.append("        default: return nil\n")
    out.append("        }\n")
    out.append("    }\n")
    out.append("}\n")
    for path, files in found:
        out.append("\nextension GoSourceLibraryText {\n")
        out.append("    static let %s: [GoSourceFile] = [\n" % property_name(path))
        for name, text in files:
            assert '"""#' not in text, name
            assert text.endswith("\n"), name
            out.append("        GoSourceFile(\n")
            out.append('            path: "$GOROOT/src/%s/%s",\n' % (path, name))
            out.append('            text: #"""\n')
            # The literal ends before its last line break: the empty line
            # keeps the one the file ends with.
            out.append(text)
            out.append('\n"""#),\n')
        out.append("    ]\n")
        out.append("}\n")
    return "".join(out)


def main():
    check = "--check" in sys.argv[1:]
    stale = []

    def settle(path, text):
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            return
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            open(path, "w", encoding="utf-8").write(text)

    settle(SORTING_FUNC, slice_family(open(SORTING, encoding="utf-8").read()))
    found = packages()
    if check and stale:
        # What the Swift file should hold includes the derived Go file.
        found = [
            (p, [(f, slice_family(open(SORTING, encoding="utf-8").read()) if (p, f) == ("sort", "zsortfunc.go") else t) for f, t in fs])
            for p, fs in found
        ]
    settle(OUTPUT, swift(found))
    for path in stale:
        print(("stale: " if check else "wrote ") + path)
    if check and stale:
        sys.exit(1)


main()
