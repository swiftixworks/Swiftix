// Generates Sources/SwiftixGoRuntime/UnicodeTables.swift from the Go standard
// library, so Swiftix Go maps case and decides printability exactly like the
// Go release it takes as its reference, whatever Unicode version the host's
// Swift runtime carries.
//
// Usage, from the repository root:
//
//	go run Scripts/generate-go-unicode-tables.go > Sources/SwiftixGoRuntime/UnicodeTables.swift

//go:build ignore

package main

import (
	"fmt"
	"runtime"
	"strconv"
	"unicode"
)

func main() {
	fmt.Printf(`/// Unicode tables of the Go standard library: the case ranges behind
/// `+"`unicode.ToUpper`"+` and `+"`unicode.ToLower`"+`, and the code points
/// `+"`strconv.IsPrint`"+` accepts.
///
/// Generated by `+"`Scripts/generate-go-unicode-tables.go`"+` from %s
/// (Unicode %s). Do not edit; regenerate when the reference Go release moves.
/// Constant data; no process or executor state.

enum GoUnicodeTables {
    /// One entry of Go's `+"`unicode.CaseRanges`"+`: the deltas to add to a code
    /// point in `+"`first...last`"+` to reach its upper, lower, and title case.
    /// A delta of `+"`alternating`"+` marks a run of upper/lower pairs.
    struct CaseRange {
        let first: UInt32
        let last: UInt32
        let toUpper: Int32
        let toLower: Int32
        let toTitle: Int32
    }

    /// Go's `+"`unicode.UpperLower`"+` marker.
    static let alternating: Int32 = %d

    static let caseRanges: [CaseRange] = [
`, runtime.Version(), unicode.Version, unicode.UpperLower)
	for _, r := range unicode.CaseRanges {
		fmt.Printf("        CaseRange(first: 0x%04X, last: 0x%04X, toUpper: %d, toLower: %d, toTitle: %d),\n",
			r.Lo, r.Hi, r.Delta[unicode.UpperCase], r.Delta[unicode.LowerCase], r.Delta[unicode.TitleCase])
	}
	fmt.Print(`    ]

    /// The printable code points as inclusive ranges: first, last, first, last...
    static let printableRanges: [UInt32] = [
`)
	start := rune(-1)
	column := 0
	emit := func(lo, hi rune) {
		if column == 0 {
			fmt.Print("       ")
		}
		fmt.Printf(" 0x%04X, 0x%04X,", lo, hi)
		column++
		if column == 4 {
			fmt.Println()
			column = 0
		}
	}
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		printable := r <= unicode.MaxRune && strconv.IsPrint(r)
		if printable && start < 0 {
			start = r
		}
		if !printable && start >= 0 {
			emit(start, r-1)
			start = -1
		}
	}
	if column != 0 {
		fmt.Println()
	}
	fmt.Println("    ]")
	fmt.Println("}")
}
