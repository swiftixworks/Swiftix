// Generates Sources/SwiftixGoRuntime/UnicodeCategoryTables.swift from the Go
// standard library, so `unicode.IsLetter`, `IsUpper`, `IsLower`, `IsDigit`,
// and `IsSpace` of Swiftix Go answer exactly like the Go release it takes as
// its reference, whatever Unicode version the host's Swift runtime carries.
//
// Usage, from the repository root:
//
//	go run Scripts/generate-go-unicode-categories.go > Sources/SwiftixGoRuntime/UnicodeCategoryTables.swift

//go:build ignore

package main

import (
	"fmt"
	"runtime"
	"unicode"
)

func table(name string, doc string, t *unicode.RangeTable) {
	fmt.Printf("\n    /// %s\n    static let %s: [UInt32] = [\n", doc, name)
	emit := func(lo, hi, stride uint32) {
		fmt.Printf("        0x%04X, 0x%04X, %d,\n", lo, hi, stride)
	}
	for _, r := range t.R16 {
		emit(uint32(r.Lo), uint32(r.Hi), uint32(r.Stride))
	}
	for _, r := range t.R32 {
		emit(r.Lo, r.Hi, r.Stride)
	}
	fmt.Printf("    ]\n")
}

func main() {
	fmt.Printf(`/// Category tables of the Go standard library: the code points
/// `+"`unicode.IsLetter`"+`, `+"`IsUpper`"+`, `+"`IsLower`"+`, `+"`IsDigit`"+`, and `+"`IsSpace`"+` accept.
///
/// Generated by `+"`Scripts/generate-go-unicode-categories.go`"+` from %s
/// (Unicode %s). Do not edit; regenerate when the reference Go release moves.
/// Constant data; no process or executor state.

enum GoUnicodeCategoryTables {
    // Each table is Go's `+"`unicode.RangeTable`"+` flattened: `+"`first, last, stride`"+` for
    // every range, in ascending order.
`, runtime.Version(), unicode.Version)
	table("letter", "`unicode.Letter`, the category L.", unicode.Letter)
	table("upper", "`unicode.Upper`, the category Lu.", unicode.Upper)
	table("lower", "`unicode.Lower`, the category Ll.", unicode.Lower)
	table("digit", "`unicode.Digit`, the category Nd.", unicode.Digit)
	table("whiteSpace", "`unicode.White_Space`.", unicode.White_Space)
	fmt.Printf("}\n")
}
